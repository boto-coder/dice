// Writes docs/fairness-report.md. Skipped in the normal test run; use `npm run fairness`.
// Unlike the seeded tests, this uses the app's real random source (crypto.getRandomValues).
import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { secureRandom } from '../../src/core/random';
import { fairnessTable, runFairness, type FairnessRun } from '../../src/physics/fairness';
import { ALPHA, COMBAT, PIPS, STANDARD_DICE, arenaFor, die } from './helpers';

const SINGLE = [
  { die: die('d4'), throws: 8000 },
  { die: die('d6'), throws: 12_000 },
  { die: die('d8'), throws: 16_000 },
  { die: die('d10'), throws: 20_000 },
  { die: die('d12'), throws: 24_000 },
  { die: die('d20'), throws: 40_000 },
  { die: die('d100'), throws: 50_000 },
  { die: COMBAT, throws: 12_000 },
  { die: PIPS, throws: 8000 },
];
const TRAY = [...STANDARD_DICE, ...STANDARD_DICE, COMBAT, COMBAT, COMBAT, PIPS, PIPS, PIPS];

function throwLine(name: string, run: FairnessRun): string {
  const t = run.throws;
  return `| ${name} | ${t.throws} | ${t.meanSeconds.toFixed(2)} s | ${t.maxSeconds.toFixed(2)} s | ${t.timeouts} (${((100 * t.timeouts) / t.throws).toFixed(1)}%) | ${(t.nudges / t.throws).toFixed(2)} |`;
}

it.skipIf(!process.env.FAIRNESS_REPORT)(
  'writes the fairness report',
  () => {
    const started = Date.now();
    const singles = SINGLE.map(({ die, throws }) => ({
      die,
      run: runFairness([die], throws, secureRandom, arenaFor(1)),
    }));
    const raw = runFairness([die('d100')], 50_000, secureRandom, arenaFor(1), {
      shuffleLabels: false,
    });
    const group = runFairness(TRAY, 2000, secureRandom, arenaFor(TRAY.length));
    const all = [...singles.flatMap((s) => s.run.reports), ...group.reports];
    const failures = all.filter((r) => r.pValue <= ALPHA).length;

    const md = `# Fairness report

_Generated by \`npm run fairness\` on ${new Date().toISOString().slice(0, 10)} in ${((Date.now() - started) / 1000).toFixed(0)} s, using the app's real random source (\`crypto.getRandomValues\`) and the same headless physics as the app._

Each die is thrown in the physics world and the face that lands on top is read exactly as in the app. A chi-square goodness-of-fit test compares the results with a fair die (custom dice with repeated faces expect those faces proportionally more often). A die **passes** when p > ${ALPHA}. With ${all.length} tests, about ${(all.length * ALPHA).toFixed(1)} would fail by chance even if everything were perfectly fair.

**Result:** ${failures === 0 ? 'every test passed' : `${failures} of ${all.length} tests had p ≤ ${ALPHA}`}.

## Single dice

${fairnessTable(singles.flatMap((s) => s.run.reports))}

## Full tray (20 mixed dice thrown together)

2 of each standard die, 3 × Combat (⚔️ ⚔️ 🛡️ 🛡️ 💀 blank, d6 shape) and 3 × Pips (1 1 2 3, d4 shape), ${group.throws.throws} throws.

${fairnessTable(group.reports)}

## The d100 ball and label shuffling

A ball with 100 faces cannot have 100 identical faces, and the physics favours some faces measurably (as with physical ball dice). Without shuffling, the faces landed like this:

${fairnessTable(raw.reports).replace('| d100 |', '| d100 (no shuffle) |')}

So the app shuffles which number is printed on which face before every d100 throw. The physics still decides which face lands on top, but the number on it is uniformly random, which makes every number exactly equally likely. The d100 row under "Single dice" is with shuffling, as in the app.

## Settling

| Throw | Throws | Mean time | Max time | Timeouts (5 s) | Nudges per throw |
| --- | ---: | ---: | ---: | ---: | ---: |
${singles.map((s) => throwLine(s.die.name, s.run)).join('\n')}
${throwLine('Full tray (20 dice)', group)}

A timed-out throw is still valid: the dice are frozen where they are and read as usual.
`;
    writeFileSync(new URL('../../docs/fairness-report.md', import.meta.url), md);
  },
  1_800_000,
);
